//! Where rebuildable data lives, and who owns it.
//!
//! Layout, startup creation, the nightly GC and the storage report all read
//! this table. A new cache is one entry here plus whatever writes into it —
//! no second list to keep in sync.
//!
//! Nothing in here is a source of truth: every file below `cache/` can be
//! deleted and rebuilt, which is why the GC policy is declared per area
//! instead of being guessed at each call site.
use std::path::{Path, PathBuf};

/// How deep the owner lives in the layout.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CacheLayout {
    /// `cache/{name}/*` — shared by every account.
    Flat,
    /// `cache/{name}/{owner}/…`
    PerOwner,
    /// `cache/{name}/{owner}/{kind}/…` (encoder / probe).
    PerOwnerPerKind,
}

/// Whether the retention GC may delete entries from this area.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CacheGc {
    /// Delete files whose last access is older than the retention window.
    FilesOlderThan,
    /// Keep: cheap to lose but expensive to rebuild (indexes, AI embeddings),
    /// or already bounded by an explicit cleanup action.
    Never,
}

#[derive(Debug, Clone, Copy)]
pub struct CacheArea {
    pub name: &'static str,
    pub layout: CacheLayout,
    pub gc: CacheGc,
}

impl CacheArea {
    pub fn root(&self, data_path: &Path) -> PathBuf {
        data_path.join("cache").join(self.name)
    }

    pub fn owner_dir(&self, data_path: &Path, owner: &str) -> PathBuf {
        self.root(data_path).join(owner)
    }
}

/// Every directory under `data/cache`. Order is presentational (storage report).
pub const CACHE_AREAS: &[CacheArea] = &[
    // Thumbnails are the only cache with an on-disk generator matrix; the
    // storage report attributes them per photo.
    CacheArea {
        name: "thumbnails",
        layout: CacheLayout::PerOwner,
        gc: CacheGc::FilesOlderThan,
    },
    CacheArea {
        name: "exif",
        layout: CacheLayout::PerOwner,
        gc: CacheGc::FilesOlderThan,
    },
    // Preview keys embed the requesting account, so each account owns a
    // directory: the same preview generated by two accounts is two files.
    CacheArea {
        name: "darktable",
        layout: CacheLayout::PerOwner,
        gc: CacheGc::FilesOlderThan,
    },
    CacheArea {
        name: "exports",
        layout: CacheLayout::Flat,
        gc: CacheGc::FilesOlderThan,
    },
    CacheArea {
        name: "video-encode",
        layout: CacheLayout::PerOwnerPerKind,
        gc: CacheGc::FilesOlderThan,
    },
    // AI embeddings drive search and face clustering; rebuilding costs minutes
    // of model time, so the retention GC leaves them alone.
    CacheArea {
        name: "ai",
        layout: CacheLayout::PerOwner,
        gc: CacheGc::Never,
    },
    // Album index files: small, and every listing reads them.
    CacheArea {
        name: "index",
        layout: CacheLayout::PerOwner,
        gc: CacheGc::Never,
    },
    // Cheap to rebuild but also tiny; the account owns exactly one.
    CacheArea {
        name: "thumbnail-manifests",
        layout: CacheLayout::PerOwner,
        gc: CacheGc::Never,
    },
    // Last storage report per account: replaced on the next scan.
    CacheArea {
        name: "storage-reports",
        layout: CacheLayout::PerOwner,
        gc: CacheGc::FilesOlderThan,
    },
];

pub fn area(name: &str) -> Option<&'static CacheArea> {
    CACHE_AREAS.iter().find(|area| area.name == name)
}

/// `data/cache` itself.
pub fn cache_root(data_path: &Path) -> PathBuf {
    data_path.join("cache")
}

#[cfg(test)]
mod tests {
    use super::{CACHE_AREAS, CacheGc, CacheLayout, area, cache_root};
    use std::collections::HashSet;
    use std::path::Path;

    #[test]
    fn names_are_unique_and_are_single_path_components() {
        let mut seen = HashSet::new();
        for area in CACHE_AREAS {
            assert!(seen.insert(area.name), "duplicate cache area {}", area.name);
            assert!(!area.name.is_empty());
            assert!(!area.name.contains(['/', '\\', '\0']));
        }
    }

    #[test]
    fn every_root_sits_under_cache() {
        let data = Path::new("/data");
        for area in CACHE_AREAS {
            let root = area.root(data);
            assert_eq!(root.parent(), Some(cache_root(data).as_path()));
        }
        assert_eq!(
            area("thumbnails").unwrap().owner_dir(data, "daniel"),
            Path::new("/data/cache/thumbnails/daniel")
        );
        assert!(area("nope").is_none());
    }

    #[test]
    fn gc_covers_exactly_the_cheap_to_rebuild_areas() {
        let aged: Vec<&str> = CACHE_AREAS
            .iter()
            .filter(|area| area.gc == CacheGc::FilesOlderThan)
            .map(|area| area.name)
            .collect();
        assert_eq!(
            aged,
            vec![
                "thumbnails",
                "exif",
                "darktable",
                "exports",
                "video-encode",
                "storage-reports",
            ]
        );
    }

    #[test]
    fn layout_matches_where_the_writers_put_files() {
        let data = Path::new("/data");
        let flat = area("exports").unwrap();
        assert_eq!(flat.layout, CacheLayout::Flat);
        assert_eq!(flat.root(data), Path::new("/data/cache/exports"));

        let previews = area("darktable").unwrap();
        assert_eq!(previews.layout, CacheLayout::PerOwner);
        assert_eq!(
            previews.owner_dir(data, "daniel"),
            Path::new("/data/cache/darktable/daniel")
        );

        let per_kind = area("video-encode").unwrap();
        assert_eq!(per_kind.layout, CacheLayout::PerOwnerPerKind);
        assert_eq!(
            per_kind.owner_dir(data, "daniel"),
            Path::new("/data/cache/video-encode/daniel")
        );
    }
}
